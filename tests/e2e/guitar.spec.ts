import { test, expect } from '@playwright/test';
test('build and reopen a guitar loop offline', async ({ page, context }) => {
  await page.goto('?view=welcome');
  await page.getByRole('link', { name: 'Гитара' }).click();
  await expect(page.getByLabel('Тональность')).toHaveValue('Am');
  await expect(page.getByLabel('Темп')).toHaveValue('120');
  await page.getByText('Как выбрать следующий аккорд?', { exact: false }).click();
  await expect(page.getByText('Сыграйте Am → Dm → Am.', { exact: false })).toBeVisible();
  await page.getByText('Как сыграть аккорд выше на грифе?', { exact: false }).click();
  await expect(page.getByText('Возьмите открытый C', { exact: false })).toBeVisible();
  await page.getByLabel('Тональность').selectOption('G');
  await page.getByLabel('Темп').selectOption('72');
  await page.getByRole('button', { name: '▷ Em' }).click();
  await page.getByText('Как выбрать форму?', { exact: true }).click();
  await expect(page.getByText('Начните с открытого Em.', { exact: false })).toBeVisible();
  await page.getByLabel('Постановка').selectOption('A');
  await expect(page.getByText('Вы играете Em. Буква A', { exact: false })).toBeVisible();
  await page.getByRole('button', { name: 'Добавить Em' }).click();
  await expect(page.getByRole('heading', { name: 'Такт 2 · Em · ми минор' })).toBeVisible();
  await expect(page.locator('.chord-chart').getByText('Em', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '1 · G', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Такт 1 · G · соль' })).toBeVisible();
  await page.getByRole('button', { name: 'Рифф', exact: true }).click();
  await page.getByLabel('Доля 4').selectOption('-1');
  await page.getByRole('button', { name: 'Послушать рифф' }).click();
  await page.getByRole('button', { name: 'Аккорды', exact: true }).click();
  await page.evaluate(async () => {
    await navigator.serviceWorker.ready;
  });
  await page.reload();
  await expect(page.getByLabel('Темп')).toHaveValue('72');
  await context.setOffline(true);
  await page.reload();
  await page.getByRole('button', { name: '2 · Em', exact: true }).click();
  await expect(page.getByLabel('Постановка')).toHaveValue('A');
  await expect(page.locator('.chord-chart').getByText('Em', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '1 · G', exact: true }).click();
  await page.getByRole('button', { name: 'Рифф', exact: true }).click();
  await expect(page.getByLabel('Доля 4')).toHaveValue('-1');
});
